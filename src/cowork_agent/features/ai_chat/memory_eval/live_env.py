"""Resolving the live tier's external dependencies (SPEC §6.1).

Three things can be missing independently: a PostgreSQL server, a Gemini key,
an embedding key. Each absence disables a specific set of scopes and
nothing else.

A harness that dies on the first missing dependency tells you nothing about the
other scopes, so every absence becomes a typed finding the report can carry.
Gemini is the one exception and it is handled by the caller: with no model
there is no reply to score, so there is no run at all.
"""

from __future__ import annotations

import asyncio
import selectors
import uuid
from collections.abc import Callable, Coroutine, Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any, TypeVar
from urllib.parse import urlsplit

from cowork_agent.config import database_url, document_embedding_provider
from cowork_agent.domain.chat_contracts import MemoryType

_CONNECT_TIMEOUT_SECONDS = 3

T = TypeVar("T")


@dataclass(frozen=True, slots=True)
class ScopeFinding:
    """One reason a scope cannot be evaluated in this run.

    Only ever constructed for a scope that is NOT usable — there is no finding
    to report about a scope that works. It carried an `available` flag once,
    which was False at every construction site and told a reader nothing.
    """

    scope: MemoryType
    reason: str


#: A throwaway chat store, never the developer's own chat.db. The harness seeds
#: its own `memeval-<key>` namespace and tears it down, so a scratch file
#: measures exactly what a shared one would while touching nothing real.
#: `evaluations/MEMORIES/runs/` is gitignored.
SQLITE_SCRATCH_PATH = Path("evaluations/MEMORIES/runs/memeval-chat.db")


@dataclass(frozen=True, slots=True)
class LiveEnvironment:
    """Which stores this run can actually reach.

    `long_term` and `episodic` are durable scopes: the product backs them with
    PostgreSQL when `database_url()` is set and with SQLite otherwise, and the
    harness has to follow that choice. Evaluating the Postgres path on a machine
    running SQLite would report two scopes unavailable while the product has
    them working — a confidently wrong answer about the system under test.
    """

    postgres_url: str | None
    sqlite_path: Path | None
    gemini_ready: bool
    embeddings_ready: bool
    embedding_key_name: str
    # Only a path generated by this harness, or an explicitly marked caller
    # path, may be deleted by the executor. A filename is never ownership.
    sqlite_path_owned: bool = False

    @property
    def durable_memory_available(self) -> bool:
        """Whether long_term and episodic have any store behind them."""

        return self.postgres_url is not None or self.sqlite_path is not None


def default_postgres_probe(url: str) -> bool:
    """True when `url` accepts a connection. Mirrors tests/integration/persistence/pg_probe."""

    if not url:
        return False
    try:
        import psycopg
    except ImportError:
        return False
    try:
        with psycopg.connect(url, connect_timeout=_CONNECT_TIMEOUT_SECONDS):
            return True
    except psycopg.Error:
        return False


def _embedding_key_name(environ: Mapping[str, str]) -> str:
    """Which API key the corpus needs, given the configured embedding provider."""

    provider = document_embedding_provider(environ, load_env_file=False)
    return "JINA_API_KEY" if provider == "jina" else "GEMINI_API_KEY"


def _embeddings_ready(environ: Mapping[str, str]) -> bool:
    """Whether the corpus can be embedded.

    The provider is chosen by DOCUMENT_EMBEDDING_PROVIDER and defaults to
    gemini, so checking a fixed key is wrong in both directions: it reports
    semantic unavailable on a working gemini setup, and reports it available on
    a jina setup holding only a gemini key.
    """

    if _embedding_key_name(environ) == "JINA_API_KEY":
        return bool(environ.get("JINA_API_KEY"))
    return _gemini_ready(environ)


def _gemini_ready(environ: Mapping[str, str]) -> bool:
    # GeminiSettings.from_env accepts GEMINI_API_KEY or numbered GEMINI_API_KEY_<n>.
    if environ.get("GEMINI_API_KEY"):
        return True
    return any(name.startswith("GEMINI_API_KEY_") and value for name, value in environ.items())


class UnsafeTargetError(RuntimeError):
    """The run was aimed at a database it must not be allowed to write to."""


#: Hosts a throwaway evaluation store may live on.
_LOCAL_HOSTS = frozenset({"localhost", "127.0.0.1", "::1"})

#: Opt-in for a remote target. Deliberately awkward to set by accident.
ALLOW_REMOTE_ENV_VAR = "MEMEVAL_ALLOW_REMOTE_POSTGRES"


def is_local_postgres(url: str) -> bool:
    """Whether `url` points at a database on this machine."""

    host = urlsplit(url).hostname
    return host is None or host in _LOCAL_HOSTS


def resolve_postgres_url(environ: Mapping[str, str]) -> str:
    """Which PostgreSQL this run should use, decided by the project's own config.

    `PG_TEST_URL` wins, so the harness can be aimed at a throwaway server the
    same way `tests/integration/persistence` is. Otherwise `database_url()`
    decides, which honours `POSTGRES_MODE` — including `off`, where it returns
    an empty string. That is the honest answer: the project is deliberately on
    SQLite, so `long_term` and `episodic` are unavailable. Guessing a default URL
    here instead would report "cannot connect" for a server nobody asked for.
    """

    return environ.get("PG_TEST_URL", "").strip() or database_url(environ)


def create_owned_sqlite_scratch(template: Path = SQLITE_SCRATCH_PATH) -> Path:
    """Allocate a unique path which this evaluation attempt owns.

    The repository creates the SQLite file lazily. Generating the random name
    here still establishes ownership before that happens, without leaving a
    file behind when a later provider preflight stops the run.
    """

    return template.with_name(f"{template.stem}-{uuid.uuid4().hex}{template.suffix}")


def probe_environment(
    environ: Mapping[str, str],
    *,
    postgres_probe: Callable[[str], bool] = default_postgres_probe,
    sqlite_path: Path | None = None,
) -> LiveEnvironment:
    """Resolve which external dependencies are actually usable right now."""

    # Mirrors app.py: a non-empty database_url() selects PostgreSQL, and its
    # absence selects SQLite. A URL that is configured but unreachable is an
    # outage, not a choice of SQLite, so it leaves both scopes with no store.
    url = resolve_postgres_url(environ)
    if url and not is_local_postgres(url) and environ.get(ALLOW_REMOTE_ENV_VAR) != "1":
        # This harness seeds memory and then deletes it. Aimed at a shared or
        # production database that is a write-and-delete against real data, so a
        # remote host has to be asked for explicitly. Failing loudly beats
        # falling back to SQLite, which would quietly measure a different store
        # than the one the run was pointed at.
        raise UnsafeTargetError(
            f"refusing to evaluate against remote database host "
            f"{urlsplit(url).hostname!r}: this harness writes and deletes memory. "
            f"Point PG_TEST_URL at a local throwaway server, set POSTGRES_MODE=off "
            f"to use a scratch SQLite file, or set {ALLOW_REMOTE_ENV_VAR}=1 if you "
            f"are certain the target is disposable."
        )
    reachable = bool(url) and postgres_probe(url)
    sqlite_scratch = None if url else sqlite_path or create_owned_sqlite_scratch()
    return LiveEnvironment(
        postgres_url=url if reachable else None,
        sqlite_path=sqlite_scratch,
        gemini_ready=_gemini_ready(environ),
        embeddings_ready=_embeddings_ready(environ),
        embedding_key_name=_embedding_key_name(environ),
        sqlite_path_owned=not url and sqlite_path is None,
    )


def unavailable_scopes(env: LiveEnvironment) -> tuple[ScopeFinding, ...]:
    """Which scopes cannot be evaluated, and why, in report-ready form.

    short_term is never listed: the session buffer is in-process, so no external
    outage can remove it.
    """

    findings: list[ScopeFinding] = []
    if not env.durable_memory_available:
        # Only reachable when a PostgreSQL URL was configured and did not
        # answer. With no URL at all the product uses SQLite and so do we, so
        # these two scopes stay evaluable.
        reason = (
            "the configured PostgreSQL is unreachable (unset it to use SQLite, as the app does)"
        )
        findings.append(ScopeFinding(MemoryType.LONG_TERM, reason))
        findings.append(ScopeFinding(MemoryType.EPISODIC, reason))
    if not env.embeddings_ready:
        findings.append(
            ScopeFinding(
                MemoryType.SEMANTIC,
                f"no {env.embedding_key_name}; corpus cannot be embedded",
            )
        )
    return tuple(findings)


def run_with_selector_loop(coro: Coroutine[Any, Any, T]) -> T:
    """Run `coro` on a selector loop.

    Windows defaults to ProactorEventLoop, which psycopg's async path does not
    support. The persistence suite does exactly this; the live tier must too or
    every database call fails on a developer machine.
    """

    return asyncio.run(
        coro, loop_factory=lambda: asyncio.SelectorEventLoop(selectors.SelectSelector())
    )
